import { Option, Result } from "effect";
import { parseFrontmatter } from "./frontmatter";
import type { Category, Repo, Skill } from "./repo";

/** Skills that carry a copy of the catalog, at `<skill>/${CATALOG_FILE}`. */
export const CATALOG_DESTINATIONS = ["imsus-ask", "imsus-setup"];
/** The catalog's path inside each destination skill folder. */
export const CATALOG_FILE = "references/catalog.md";

const HEADER = "| Skill | Category | Description | Source |\n| --- | --- | --- | --- |";

/** A table cell: one line, with `|` escaped. */
const cell = (text: string) => text.replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|").trim();

const description = (skill: Skill) =>
  Option.match(skill.skillMd, {
    onNone: () => "",
    onSome: (md) => parseFrontmatter(md)?.description ?? "",
  });

const source = (skill: Skill) => {
  if (skill._tag === "Own") return "own";
  return Result.match(skill.upstream, {
    onSuccess: (u) => `fork of ${u.repo}`,
    onFailure: () => "fork",
  });
};

/**
 * Build the skill catalog text from the folder tree: per category its
 * description, plugin and `npx skills` install lines, and one row per skill.
 * Like the marketplace manifest, a category whose metadata did not load is left out.
 */
export function generateCatalog(repo: Repo): string {
  const sections = repo.categories.flatMap((cat) => (cat.meta._tag === "Loaded" ? [section(cat, cat.meta.description)] : []));
  return [
    "# Skill catalog\n",
    "Generated by `bun run manifest` from the folder tree. Do not edit by hand.\n",
    ...sections,
  ].join("\n");
}

function section(cat: Category, about: unknown): string {
  const intro = typeof about === "string" ? `${cell(about)}\n\n` : "";
  const skillFlags = cat.skills.map((s) => ` --skill ${s.name}`).join("");
  const rows = cat.skills.map((s) => `| ${s.name} | ${cat.name} | ${cell(description(s))} | ${source(s)} |`);
  return [
    `## ${cat.name}\n\n${intro}\`\`\``,
    `/plugin install ${cat.name}@imsus`,
    `npx skills add imsus/skills${skillFlags}`,
    "```\n",
    HEADER,
    ...rows,
    "",
  ].join("\n");
}
