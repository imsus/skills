import { afterEach, expect, test } from "bun:test";
import { existsSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CATALOG_COPIES, metaCategory } from "./helpers/catalog";
import { fork, upstreamMd } from "./helpers/fork";
import { categoryWith } from "./helpers/manifest";
import { buildTree, category, read, runCli, skillMd, type Tree } from "./helpers/tree";

let tree: Tree;
afterEach(() => tree?.cleanup());


test("manifest writes the same catalog into imsus-ask and imsus-setup", async () => {
  tree = buildTree({
    ...metaCategory(),
    ...categoryWith("web", ["imsus-a"], "Web stuff.", "2.1.0"),
    "skills/web/imsus-a/SKILL.md": skillMd("imsus-a", "Builds | pages."),
    ...fork("web", "imsus-forked", { upstream: upstreamMd({ repo: "someone/their-skills" }) }),
  });
  expect((await runCli(["manifest"], tree.root)).code).toBe(0);
  const [ask, setup] = CATALOG_COPIES.map((copy) => read(tree, copy));
  expect(ask).toBe(setup!);
  expect(ask).toBe(
    [
      "# Skill catalog",
      "",
      "Generated by `bun run manifest` from the folder tree. Do not edit by hand.",
      "",
      "## meta",
      "",
      "A category.",
      "",
      "```",
      "/plugin install meta@imsus",
      "npx skills add imsus/skills --skill imsus-ask --skill imsus-setup",
      "```",
      "",
      "| Skill | Category | Description | Upstream |",
      "| --- | --- | --- | --- |",
      "| imsus-ask | meta | Does a thing. | own |",
      "| imsus-setup | meta | Does a thing. | own |",
      "",
      "## web",
      "",
      "Web stuff.",
      "",
      "```",
      "/plugin install web@imsus",
      "npx skills add imsus/skills --skill imsus-a --skill imsus-forked",
      "```",
      "",
      "| Skill | Category | Description | Upstream |",
      "| --- | --- | --- | --- |",
      "| imsus-a | web | Builds \\| pages. | own |",
      "| imsus-forked | web | Does a thing. | fork of someone/their-skills |",
      "",
    ].join("\n"),
  );
});

test("no catalog is written when imsus-ask and imsus-setup are absent", async () => {
  tree = buildTree(category("web", ["imsus-a"]));
  expect((await runCli(["manifest"], tree.root)).code).toBe(0);
  for (const copy of CATALOG_COPIES) expect(existsSync(join(tree.root, copy))).toBe(false);
});

test("check passes right after manifest", async () => {
  tree = buildTree({ ...metaCategory(), ...category("web", ["imsus-a"]) });
  await runCli(["manifest"], tree.root);
  const r = await runCli(["manifest", "--check"], tree.root);
  expect(r.code).toBe(0);
});

test("check fails when the catalog is stale", async () => {
  tree = buildTree({ ...metaCategory(), ...category("web", ["imsus-a"]) });
  await runCli(["manifest"], tree.root);
  writeFileSync(join(tree.root, "skills/web/imsus-a/SKILL.md"), skillMd("imsus-a", "Now does another thing."));
  const r = await runCli(["manifest", "--check"], tree.root);
  expect(r.code).toBe(1);
  for (const copy of CATALOG_COPIES) expect(r.stderr).toContain(`${copy} is stale`);
  expect(r.stderr).not.toContain(".claude-plugin/marketplace.json is stale");
});

test("check fails when one catalog copy differs from the other", async () => {
  tree = buildTree(metaCategory());
  await runCli(["manifest"], tree.root);
  const [ask, setup] = CATALOG_COPIES;
  writeFileSync(join(tree.root, ask!), read(tree, ask!) + "Hand edit.\n");
  const r = await runCli(["manifest", "--check"], tree.root);
  expect(r.code).toBe(1);
  expect(r.stderr).toContain(`${ask} is stale`);
  expect(r.stderr).not.toContain(`${setup} is stale`);
});

test("check fails when a catalog copy is missing", async () => {
  tree = buildTree(metaCategory());
  await runCli(["manifest"], tree.root);
  rmSync(join(tree.root, CATALOG_COPIES[1]!));
  const r = await runCli(["manifest", "--check"], tree.root);
  expect(r.code).toBe(1);
  expect(r.stderr).toContain(`${CATALOG_COPIES[1]} is stale`);
});
